#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Prints the release notes for one tag on stdout; the release workflow redirects
# that into a file and hands it to the GitHub release as `body_path`.
#
#   scripts/release-notes.sh v0.1.0
#
# Where the body comes from, in order:
#
#   1. CHANGELOG.md, if it exists and holds a section for this tag. A heading is
#      recognised as `## [v0.1.0]`, `## v0.1.0`, `## [0.1.0]` or `## 0.1.0`, with
#      an optional trailing ` - 2026-09-11`. The section runs to the next `## `.
#   2. Otherwise the commit subjects since the previous `v*` tag, or the whole
#      log when this is the first tag.
#
# After the body comes an `## API changes` section, whichever source the body
# used: `oasdiff changelog` (the version go.mod pins as a tool) diffs this
# tag's docs/openapi.json against the previous release's, in markdown. A full
# release — a tag without a hyphen — compares against the previous full
# release, so someone upgrading sees the whole delta rather than the change
# since the last rc; a pre-release compares against the previous `v*` tag of
# any kind. Breaking changes are listed first under a heading of their own,
# then the whole changelog. The section degrades to prose rather than
# failing: no earlier tag, no contract at it or on this tag, an empty diff,
# and an oasdiff error each get a line of their own.
#
# The images are named last, because the two images are the release and a
# reader needs the lines that pull them.
set -euo pipefail

tag="${1:-}"
if [ -z "$tag" ]; then
	echo "usage: $(basename "$0") <tag>" >&2
	exit 2
fi

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

# The tag with any leading `v` removed, so a CHANGELOG written either way matches.
bare="${tag#v}"

changelog_section() {
	[ -f CHANGELOG.md ] || return 1
	awk -v tag="$tag" -v bare="$bare" '
		function is_heading(line,    body) {
			if (line !~ /^## /) return 0
			body = substr(line, 4)
			sub(/^[ \t]+/, "", body)
			sub(/[ \t]+$/, "", body)
			# Drop an optional trailing " - <date>" or " — <date>". The dash has
			# to be set off by whitespace: the hyphen in v0.1.0-rc.1 is the tag.
			sub(/[ \t]+[-–—].*$/, "", body)
			sub(/[ \t]+$/, "", body)
			# Drop the brackets of a Keep-a-Changelog style heading.
			if (body ~ /^\[.*\]$/) body = substr(body, 2, length(body) - 2)
			heading = body
			return 1
		}
		{
			if (is_heading($0)) {
				if (inside) exit
				if (heading == tag || heading == bare) { inside = 1; found = 1; next }
				next
			}
			if (inside) print
		}
		END { exit(found ? 0 : 1) }
	' CHANGELOG.md
}

previous_tag() {
	git describe --tags --abbrev=0 --match 'v*' "${tag}^" 2>/dev/null || true
}

# The previous full release: `git describe` walks one tag at a time backwards,
# skipping hyphenated (pre-release) names, so describe's own notion of
# "nearest tag" is kept rather than a version sort.
previous_full_tag() {
	local rev prev
	rev="${tag}^"
	while prev="$(git describe --tags --abbrev=0 --match 'v*' "$rev" 2>/dev/null)" && [ -n "$prev" ]; do
		case $prev in
		*-*) rev="${prev}^" ;;
		*) printf '%s\n' "$prev"; return 0 ;;
		esac
	done
	return 0
}

commit_log() {
	local prev
	prev="$(previous_tag)"
	if [ -n "$prev" ]; then
		echo "## Changes since ${prev}"
		echo
		git log --no-merges --format='- %s (%h)' "${prev}..${tag}"
	else
		echo "## Changes in ${tag}"
		echo
		git log --no-merges --format='- %s (%h)' "${tag}"
	fi
}

# oasdiff's markdown opens with `# API Changelog <a> vs. <b>` and lists the
# entries under `## API Changes`. Both headings are dropped — the section
# carries its own — every remaining heading is demoted under the section's
# h3s, and blank runs collapse into one blank line.
oasdiff_body() {
	awk '
		/^# /              { next }
		/^## API Changes$/ { next }
		/^##+ /            { sub(/^##+/, "####") }
		/[^ \t]/           { if (started && pending) print ""; print; started = 1; pending = 0; next }
		                   { pending = 1 }
	'
}

# The section once both specs are in hand. `### Breaking changes` holds the
# ERR-level changelog (`--level ERR` is oasdiff's breaking set); `### All
# changes` is the whole changelog, so a breaking entry appears twice — first
# labelled, then in context.
api_changes_diff() {
	local prev="$1" desc="$2" old_spec="$3" new_spec="$4"
	local changelog breaking
	printf '`docs/openapi.json` compared with `%s` (%s), generated by `oasdiff changelog`.\n\n' "$prev" "$desc"

	if ! changelog="$(go tool oasdiff changelog "$old_spec" "$new_spec" --format markdown)"; then
		echo '_`oasdiff` failed to diff the two contracts; the job log has its error._'
		return 0
	fi
	# A changelog without a single entry heading is oasdiff saying "No changes
	# detected" or "No changes to report, but the specs are different".
	if ! printf '%s\n' "$changelog" | grep -qE '^#{2,} '; then
		echo 'No API changes.'
		return 0
	fi

	echo '### Breaking changes'
	echo
	if ! breaking="$(go tool oasdiff changelog "$old_spec" "$new_spec" --format markdown --level ERR)"; then
		echo '_`oasdiff` failed to diff the two contracts; the job log has its error._'
	elif printf '%s\n' "$breaking" | grep -q '^### '; then
		printf '%s\n' "$breaking" | oasdiff_body
	else
		echo 'None.'
	fi
	echo
	echo '### All changes'
	echo
	printf '%s\n' "$changelog" | oasdiff_body
	return 0
}

api_changes() {
	local prev desc
	case $tag in
	*-*)
		prev="$(previous_tag)"
		desc='the previous release'
		;;
	*)
		prev="$(previous_full_tag)"
		desc='the previous full release'
		;;
	esac

	echo
	echo '## API changes'
	echo
	if [ -z "$prev" ]; then
		echo 'No previous release to compare `docs/openapi.json` against.'
		return 0
	fi

	local spec_dir old_spec new_spec
	spec_dir="$(mktemp -d)"
	old_spec="$spec_dir/old.json"
	new_spec="$spec_dir/new.json"
	if ! git show "${prev}:docs/openapi.json" >"$old_spec" 2>/dev/null; then
		echo 'No previous release to compare `docs/openapi.json` against.'
	elif ! git show "${tag}:docs/openapi.json" >"$new_spec" 2>/dev/null; then
		echo 'No API changes.'
	else
		api_changes_diff "$prev" "$desc" "$old_spec" "$new_spec"
	fi
	rm -rf "$spec_dir"
}

body="$(changelog_section || true)"
if [ -n "${body//[[:space:]]/}" ]; then
	# Trim the blank lines a section picks up at either end.
	printf '%s\n' "$body" | awk '
		{ lines[NR] = $0; if ($0 ~ /[^ \t]/) { if (!first) first = NR; last = NR } }
		END { for (i = first; i <= last; i++) print lines[i] }'
else
	commit_log
fi

api_changes

cat <<EOF

## The images

\`\`\`sh
docker pull rasonyang/ai-native-callcenter:${tag}
docker pull rasonyang/freeswitch-aicc:${tag}
\`\`\`

Both \`linux/amd64\` and \`linux/arm64\`, built from the same commit. The
application image is one executable with the SPA inside it and nothing else;
the switch image is FreeSWITCH with this release's configuration and Lua
scripts. Run them together: they share the \`luacc.*\` contract, and a switch
from another release breaks phone registration. Only exact tags are published —
there is no \`latest\`, so a deployment names the build it runs.

Point \`AICC_IMAGE\` and \`AICC_FS_IMAGE\` at them and the stack pulls instead
of building; [deploy/README.md](deploy/README.md) is the whole procedure.
EOF
